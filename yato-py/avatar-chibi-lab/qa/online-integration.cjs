'use strict';
const {app,BrowserWindow,screen,shell}=require('electron');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const Target=require('../display-target.cjs'),BubbleHost=require('../bubble-host.cjs');
const pause=ms=>new Promise(r=>setTimeout(r,ms));
const until=async f=>{const end=Date.now()+5000;while(!await f()){if(Date.now()>end)throw Error('Timeout');await pause(20);}};
const timer=setTimeout(()=>app.exit(1),20000);
app.whenReady().then(async()=>{
  const display=Target.selectDisplay(screen),saved=[];
  const parent=new BrowserWindow({...Target.windowBounds(display,{width:225,height:375}),show:false,webPreferences:{offscreen:true}});
  await parent.loadURL('data:text/html,<body>QA</body>');
  const host=new BubbleHost({parent,getDisplay:()=>display,settings:{onlineInfo:true},saveSettings:x=>saved.push(x),hidden:true});
  const js=s=>host.window.webContents.executeJavaScript(s);await until(()=>host.ready);
  const info={kind:'news',text:'Exemplo de teste: novidades sobre inteligência artificial.',source:'Canaltech',link:'https://canaltech.com.br/inteligencia-artificial/',published:Date.now(),fetchedAt:Date.now(),id:'qa-news'};
  let resolve;host.online.get=()=>new Promise(r=>{resolve=r;});host.online.startAt=0;
  const pending=host.pollOnline();assert(host.online.pending);
  host.setText('Resposta do chat tem prioridade.',1);resolve(info);await pending;
  assert.equal(host.model.message.kind,'answer');assert.equal(saved.length,0);
  host.setText('',2);host.online.retryAt=0;host.online.get=async()=>info;
  await host.pollOnline();assert.equal(host.model.message.info.source,'Canaltech');assert.equal(saved[0].onlineHistory.newsCount,1);
  await until(()=>js('!document.getElementById("source-row").hidden'));
  assert.match(await js('document.getElementById("source-label").textContent'),/Canaltech/);
  assert(host.safeSource(info.link));assert(!host.safeSource('javascript:alert(1)'));assert(!host.safeSource('https://canaltech.com.br.evil.test/'));
  let opened;const original=shell.openExternal;shell.openExternal=async url=>{opened=url;};
  await js('document.getElementById("source").click()');await until(()=>opened);assert.equal(opened,info.link);shell.openExternal=original;
  await host.showOnline('weather');assert(host.editing);assert(host.window.isFocusable());
  host.window.webContents.invalidate();await pause(200);
  assert(await js('document.body.scrollHeight<=innerHeight+1'));
  fs.writeFileSync(path.join(__dirname,'online-preview.png'),(await host.window.webContents.capturePage()).toPNG());
  assert(Target.contains(display,host.window.getBounds()));
  await js('document.getElementById("close").click()');await until(()=>!host.editing);
  host.online.startAt=0;host.online.retryAt=0;host.online.settings.onlineHistory={};host.online.get=async()=>{throw Error('offline');};
  await host.pollOnline();assert(host.online.retryAt>Date.now());assert.equal(host.model.message,null);
  host.destroy();parent.destroy();clearTimeout(timer);
  const result={ok:true,monitor:display.id,checks:['late news never overwrites chat','quota recorded only when shown','source and timestamp','source URL validation','source button mocked','manual consultation','fits bubble','passive focus restored','offline retry without invented content']};
  fs.writeFileSync(path.join(__dirname,'online-integration-result.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));app.quit();
}).catch(e=>{console.error(e);app.exit(1);});app.on('window-all-closed',()=>{});
