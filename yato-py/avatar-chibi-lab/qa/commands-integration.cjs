'use strict';
const {app,BrowserWindow,screen}=require('electron');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const Target=require('../display-target.cjs'),BubbleHost=require('../bubble-host.cjs');
const pause=ms=>new Promise(r=>setTimeout(r,ms));
const until=async condition=>{const end=Date.now()+6000;while(!await condition()){if(Date.now()>end)throw Error('Timed out');await pause(30);}};
const timeout=setTimeout(()=>app.exit(1),25000);
app.whenReady().then(async()=>{
  const display=Target.selectDisplay(screen),saved=[],calls=[];
  const parent=new BrowserWindow({...Target.windowBounds(display,{width:225,height:375}),show:false,webPreferences:{offscreen:true}});
  await parent.loadURL('data:text/html,<html><body>QA</body></html>');
  const host=new BubbleHost({parent,getDisplay:()=>display,hidden:true,saveSettings:x=>saved.push(x)});
  host.commands.shell={openExternal:async u=>calls.push(u),openPath:async p=>{calls.push(p);return '';}};
  host.commands.dialog={showOpenDialog:async()=>({canceled:true,filePaths:[]})};
  host.commands.resolve=async()=>app.getPath('temp');
  const js=code=>host.window.webContents.executeJavaScript(code);
  await until(()=>host.ready);host.setText('Resposta original do chat.',1);host.compose();
  await until(()=>js('!document.getElementById("command-form").hidden'));
  assert(host.window.isFocusable());assert(host.hovered);assert(Target.contains(display,host.window.getBounds()));
  assert(!host.window.isVisible());
  await js('document.getElementById("command-input").value="abre o Google";document.getElementById("command-form").requestSubmit()');
  await until(async()=>await js('document.getElementById("message").textContent')==='Google aberto no navegador.');
  assert.deepEqual(calls,['https://www.google.com/']);
  await js('document.getElementById("command-input").value="quanto é 18 vezes 27?";document.getElementById("command-form").requestSubmit()');
  await until(async()=>await js('document.getElementById("message").textContent')==='O resultado é 486.');
  assert.equal(await js('document.getElementById("command-input").value'),'');
  const remaining=host.model.message.remaining;host.tick(1);assert.equal(host.model.message.remaining,remaining);
  await js('document.getElementById("command-input").value="abre o explorador de arquivos na pasta jogos";document.getElementById("command-form").requestSubmit()');
  await until(()=>calls.length===2);assert.equal(calls[1],app.getPath('temp'));
  host.window.webContents.invalidate();await pause(400);
  fs.writeFileSync(path.join(__dirname,'commands-preview.png'),(await host.window.webContents.capturePage()).toPNG());
  assert(await js('document.body.scrollHeight<=innerHeight+1'));
  await js('document.getElementById("close").click()');await until(()=>!host.editing);
  assert(!host.window.isFocusable());assert(host.model.revisit());assert.equal(host.model.view().text,'Resposta original do chat.');
  host.compose();host.configure({bubblesEnabled:false});assert(!host.editing);assert(!host.window.isFocusable());
  host.configure({bubblesEnabled:true});
  const longText='Uma notícia longa de jogos, IA e tecnologia. '.repeat(30);
  host.setText(longText,2);
  await until(async()=>await js('document.getElementById("message").textContent')===longText);
  await until(async()=>await js('!document.getElementById("expand").hidden'));
  await js('document.getElementById("expand").click()');
  await until(async()=>await js('document.getElementById("bubble").classList.contains("expanded")'));
  await pause(150);
  assert(await js('document.body.scrollHeight<=innerHeight+1'));
  assert(Target.contains(display,host.window.getBounds()));
  await js('document.getElementById("expand").click()');
  host.destroy();parent.destroy();
  const result={ok:true,monitor:display.id,checks:['real IPC form submit','focus only for explicit commands','typing pauses expiration and walking','Google and folder dispatch mocked','folder jogos resolved','close restores passive window','chat response retained','fits window','disable while composing']};
  fs.writeFileSync(path.join(__dirname,'commands-integration-result.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));clearTimeout(timeout);app.quit();
}).catch(e=>{console.error(e);app.exit(1);});
app.on('window-all-closed',()=>{});
